  /* one line: "<name>\t<zip>:<blocks in base36>[,<zip>:...]". A block list "1w-4" is
     base36 68 plus four — blocks 68..72, which is house numbers 6800-7299. */
  function parseStreets(text) {
    var lines = String(text || '').split('\n');
    var out = [];
    for (var i = 0; i < lines.length; i++) {
      var tab = lines[i].indexOf('\t');
      if (tab < 1) continue;
      var name = lines[i].slice(0, tab);
      var parts = lines[i].slice(tab + 1).split(',');
      var zips = [];
      for (var j = 0; j < parts.length; j++) {
        if (parts[j].charAt(5) !== ':') continue;
        var zip = parts[j].slice(0, 5);
        if (!/^\d{5}$/.test(zip)) continue;
        var bs = parts[j].slice(6).split('.');
        var blocks = [];
        for (var k = 0; k < bs.length; k++) {
          var d = bs[k].indexOf('-');
          var lo = parseInt(d < 0 ? bs[k] : bs[k].slice(0, d), 36);
          var hi = d < 0 ? lo : lo + parseInt(bs[k].slice(d + 1), 36);
          if (isFinite(lo) && isFinite(hi) && hi >= lo) blocks.push([lo, hi]);
        }
        if (blocks.length) zips.push({ zip: zip, blocks: blocks });
      }
      if (zips.length) out.push({ name: name, up: name.toUpperCase(), zips: zips });
    }
    return out;
  }

