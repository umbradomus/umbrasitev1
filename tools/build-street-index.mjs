/* SITE-ADDRESS-SUGGEST-01 · BUILD THE STREET LIST THE ADDRESS STEP SUGGESTS FROM.
   Nobody edits assets/ud-streets.js by hand. It is generated from ONE public-domain file:

     https://www2.census.gov/geo/tiger/TIGER2024/ADDRFEAT/tl_2024_48061_addrfeat.zip
     (US Census Bureau TIGER/Line Address Features, Cameron County TX, FIPS 48061)

   No key, no account, no charge, and the customer's phone never asks the Census for it -
   it is read here, once, and what ships is the condensed list.

   Run:  node tools/build-street-index.mjs <dir holding the unzipped *_addrfeat.dbf>
   Out:  assets/ud-streets.js

   It THROWS rather than ship a short or silent list: the checks at the bottom are the
   contract, and they are shown able to fail. */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const SRC = process.argv[2];
const OUT = path.resolve('assets/ud-streets.js');
if (!SRC) { console.error('usage: node tools/build-street-index.mjs <dir>'); process.exit(2); }

const found = fs.readdirSync(SRC).find((f) => /_addrfeat\.dbf$/.test(f));
if (!found) throw new Error('no *_addrfeat.dbf in ' + SRC);

/* ---- the .dbf: one record per street segment, the house-number range on each side ---- */
const dbf = fs.readFileSync(path.join(SRC, found));
const recs = dbf.readUInt32LE(4), hl = dbf.readUInt16LE(8), rl = dbf.readUInt16LE(10);
const F = {};
{
  let off = 0;
  for (let o = 32; dbf[o] !== 0x0d && o < hl; o += 32) {
    F[dbf.toString('latin1', o, o + 11).replace(/\0.*$/, '')] = { off, len: dbf[o + 16] };
    off += dbf[o + 16];
  }
}
for (const need of ['FULLNAME', 'LFROMHN', 'LTOHN', 'RFROMHN', 'RTOHN', 'ZIPL', 'ZIPR'])
  if (!F[need]) throw new Error('the .dbf has no ' + need + ' — this is not an ADDRFEAT file');
const cell = (r, n) =>
  dbf.toString('latin1', hl + r * rl + 1 + F[n].off, hl + r * rl + 1 + F[n].off + F[n].len).trim();

/* ---- street + ZIP -> the hundred-blocks that street has in that ZIP ---- */
const pairs = new Map();
let ranges = 0, skippedName = 0;
for (let i = 0; i < recs; i++) {
  const name = cell(i, 'FULLNAME');
  if (!name) continue;
  /* A name carrying a comma or a tab cannot live on a line of this format. TIGER carries
     exactly one in this county and it is a person's name, which has no business in a
     shipped file either way. */
  if (/[,\t]/.test(name)) { skippedName++; continue; }
  for (const s of [['ZIPL', 'LFROMHN', 'LTOHN'], ['ZIPR', 'RFROMHN', 'RTOHN']]) {
    const zip = cell(i, s[0]);
    if (!/^\d{5}$/.test(zip)) continue;
    const lo = parseInt(cell(i, s[1]), 10), hi = parseInt(cell(i, s[2]), 10);
    if (!Number.isFinite(lo) || !Number.isFinite(hi)) continue;
    const k = name + '|' + zip;
    let e = pairs.get(k);
    if (!e) { e = { name, zip, b: [] }; pairs.set(k, e); }
    e.b.push([Math.floor(Math.min(lo, hi) / 100), Math.floor(Math.max(lo, hi) / 100)]);
    ranges++;
  }
}

/* ---- one line per street name, every ZIP it touches on it ---- */
const byName = new Map();
for (const e of pairs.values()) {
  e.b.sort((a, b) => a[0] - b[0]);
  const m = [];
  for (const b of e.b) {
    const last = m[m.length - 1];
    if (last && b[0] <= last[1] + 1) last[1] = Math.max(last[1], b[1]); else m.push([b[0], b[1]]);
  }
  if (!m.length) continue;
  if (!byName.has(e.name)) byName.set(e.name, []);
  byName.get(e.name).push(e.zip + ':' +
    m.map((b) => b[0].toString(36) + (b[1] > b[0] ? '-' + (b[1] - b[0]).toString(36) : '')).join('.'));
}
const lines = [...byName.keys()].sort().map((n) => n + '\t' + byName.get(n).join(','));
const body = lines.join('\n');

/* ---- the contract. It must be able to fail, and it is: see 30-index-checks-RED.txt ---- */
const bonham = (byName.get('Bonham Rd') || []).join(',');
const must = [
  ['at least 3000 street names', lines.length >= 3000, lines.length],
  ['Bonham Rd is in it', byName.has('Bonham Rd'), bonham],
  ['6833 is inside a Bonham Rd block in 78521', /(^|,)78521:1w(-|,|$)/.test(bonham), bonham],
  ['every line is <name>TAB<zip>:…', lines.every((l) => /^[^\t]+\t\d{5}:[0-9a-z.\-,:]+$/.test(l)), 'all ' + lines.length],
  ['no name carries a comma or a tab', lines.every((l) => !/[,]/.test(l.split('\t')[0])), 'all ' + lines.length],
  ['no digit sequence longer than 5 anywhere (no phone number, no person)', !/\d{6,}/.test(body), 'ok'],
  ['under 200 KB raw', Buffer.byteLength(body, 'latin1') < 200000, Buffer.byteLength(body, 'latin1')],
];
let bad = 0;
for (const [what, ok, saw] of must) {
  console.log((ok ? 'PASS  ' : 'FAIL  ') + what + '  — ' + JSON.stringify(saw));
  if (!ok) bad++;
}
console.log('--- RESULT ---');
if (bad) { console.log('RESULT: FAIL  pass ' + (must.length - bad) + '  fail ' + bad + '\nassets/ud-streets.js NOT written'); process.exit(1); }

const js = '/* GENERATED by tools/build-street-index.mjs from US Census Bureau TIGER/Line ADDRFEAT,\n' +
  '   Cameron County TX (FIPS 48061), TIGER2024. Public domain — no key, no account, no charge.\n' +
  '   DO NOT EDIT BY HAND. ' + lines.length + ' street names, ' + pairs.size + ' street+ZIP pairs.\n' +
  '   Each line: <street name>\t<zip>:<hundred-blocks in base36>[,<zip>:…]\n' +
  '   A block list "1w-4" is base36 68 plus four: blocks 68..72, i.e. house numbers 6800-7299. */\n' +
  'window.UMBRA_STREETS = ' + JSON.stringify(body) + ';\n';
fs.writeFileSync(OUT, js, 'latin1');
console.log('RESULT: PASS  pass ' + must.length + '  fail 0');
console.log('names ' + lines.length + '  street+ZIP ' + pairs.size + '  ranges ' + ranges +
  '  names dropped for a comma ' + skippedName +
  '  raw ' + Buffer.byteLength(body, 'latin1') + 'B  gzip ' +
  zlib.gzipSync(Buffer.from(body, 'latin1'), { level: 9 }).length + 'B  file ' + fs.statSync(OUT).size + 'B');
